def atomic_mass(z):
    """Standard atomic weight of element z (1..118) in u."""
    if not 1 <= z <= len(ATOMIC_MASSES):
        raise ValueError(f"no atomic mass for Z = {z}")
    return ATOMIC_MASSES[z - 1]


