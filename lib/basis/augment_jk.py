"""Generate aug-cc-pVXZ-JK from cc-pVXZ-JK (not available from the Basis Set Exchange).

For each element and angular momentum one diffuse function is added: the even-tempered
extension a_min^2 / a_2nd of the two smallest exponents, or a / 2.5 if the angular
momentum has a single exponent. This reproduces Molpro's aug-cc-pVTZ/JKFIT (AVTZ/JKFIT):
water aug-cc-pVTZ DF-RHF energy and CABS singles agree to 1e-11 Eh
(reference_f12/h2o-dfmp2-testcabs-molpro, tests/test_cabs.py).

Usage: python augment_jk.py  (writes aug-cc-pVXZ-JK.json, X = T, Q, 5, here)
"""

import json
from pathlib import Path

HERE = Path(__file__).parent
SINGLE_RATIO = 2.5


def augment(data, name):
    """BSE JSON dict of cc-pVXZ-JK -> aug-cc-pVXZ-JK (one diffuse shell per l and element)."""
    out = json.loads(json.dumps(data))
    for el in out["elements"].values():
        shells = el.get("electron_shells", [])
        by_l = {}
        for s in shells:
            for l in s["angular_momentum"]:
                by_l.setdefault(l, set()).update(float(x) for x in s["exponents"])
        for l in sorted(by_l):
            e = sorted(by_l[l])
            a = e[0] ** 2 / e[1] if len(e) > 1 else e[0] / SINGLE_RATIO
            last = max(i for i, s in enumerate(shells) if l in s["angular_momentum"])
            shells.insert(last + 1, {"function_type": "gto_spherical", "region": "",
                                     "angular_momentum": [l], "exponents": [f"{a:.10E}"],
                                     "coefficients": [["1.0000000"]]})
    base = data["name"]
    out["name"] = name
    out["names"] = [name]
    out["description"] = (f"{base} augmented by one diffuse function per angular momentum "
                          f"(generated by gemQC lib/basis/augment_jk.py; reproduces Molpro "
                          f"aug-cc-pVXZ/JKFIT)")
    out["revision_description"] = (
        f"gemQC: generated from {base} ({data.get('revision_description', '')}): per element "
        f"and l one diffuse exponent a_min^2/a_2nd (even-tempered extension), a/"
        f"{SINGLE_RATIO} for a single exponent; not from the Basis Set Exchange")
    out["family"] = data.get("family", "")
    return out


if __name__ == "__main__":
    for x in ("T", "Q", "5"):
        src = json.loads((HERE / f"cc-pV{x}Z-JK.json").read_text())
        name = f"aug-cc-pV{x}Z-JKFIT"
        (HERE / f"aug-cc-pV{x}Z-JK.json").write_text(json.dumps(augment(src, name), indent=1)
                                                    + "\n")
        print(f"aug-cc-pV{x}Z-JK.json written")
